#!/usr/bin/env node
'use strict';

/**
 * Harvest Vertex ADT catalogs from the Node language server into server/catalog/*.json
 * and regenerate committed C++ under server/src/generated/.
 * Do not hand-author the JSON or the generated C++. CMake does not run this script.
 */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const CUSTOM_VALIDATORS = Object.freeze([
    'abs',
    'dbcreate',
    'get_area_param',
    'new_iterator',
    'pnt_to_plane',
]);

const KIND_BY_PREDICATE = Object.freeze({
    isValidNormalVariable: 'normal variable',
    isValidStringVariable: 'string variable',
    isValidAnyVariable: 'any variable',
    isValidStringExpression: 'string expression',
});

const ROOT = path.resolve(__dirname, '..');
const SERVER_JS = path.join(ROOT, 'server', 'out', 'server.js');
const CATALOG_DIR = path.join(ROOT, 'server', 'catalog');
const GENERATED_DIR = path.join(ROOT, 'server', 'src', 'generated');
const GENERATED_BANNER = [
    '// GENERATED FILE — do not hand-edit.',
    '// Regenerated by: npm run harvest-catalogs',
    '',
].join('\n');

function main() {
    const harvested = harvestFromNode(fs.readFileSync(SERVER_JS, 'utf8'));
    writeCatalogJson(harvested);
    writeGeneratedCpp(harvested);
    assertHarvest(harvested);
    console.log(summarize(harvested));
}

function harvestFromNode(serverSource) {
    const live = evalNodeCatalogs(serverSource);
    const commands = {};
    for (const name of Object.keys(live.commandValidations)) {
        try {
            commands[name] = harvestCommand(name, live.commandValidations[name]);
        } catch (err) {
            err.message = `${name}: ${err.message}`;
            throw err;
        }
    }
    return {
        commands: applyNativeCommandOverrides(commands),
        keywords: harvestKeywords(live.keywords),
        commandTypeWrites: {
            returnTypeMap: applyNativeReturnTypeOverrides(live.returnTypeMap),
            inputParamTypeMap: live.inputParamTypeMap,
            paramTypeMap: stringifyNumericKeys(live.paramTypeMap),
            multiParamTypeMap: stringifyNumericKeys(live.multiParamTypeMap),
        },
        objectParameters: harvestObjectParameters(live.parameterConfigurations),
    };
}

function writeCatalogJson(harvested) {
    fs.mkdirSync(CATALOG_DIR, { recursive: true });
    writeJson(path.join(CATALOG_DIR, 'commands.json'), harvested.commands);
    writeJson(path.join(CATALOG_DIR, 'keywords.json'), harvested.keywords);
    writeJson(path.join(CATALOG_DIR, 'command-type-writes.json'), harvested.commandTypeWrites);
    writeJson(path.join(CATALOG_DIR, 'object-parameters.json'), harvested.objectParameters);
}

// parameterConfigurations: command → objectType → rows, in Node's key and row
// order. Empty arrays stay: a present empty list wins the lookup.
function harvestObjectParameters(configurations) {
    const out = {};
    for (const command of Object.keys(configurations)) {
        out[command] = {};
        for (const objectType of Object.keys(configurations[command])) {
            out[command][objectType] = configurations[command][objectType].map((row) => {
                for (const key of Object.keys(row)) {
                    if (!['label', 'documentation', 'detail', 'insertText'].includes(key)) {
                        throw new Error(`${command}/${objectType}: unknown row key ${key}`);
                    }
                    if (typeof row[key] !== 'string') {
                        throw new Error(`${command}/${objectType}: ${key} is not a string`);
                    }
                }
                const harvestedRow = { label: row.label };
                for (const key of ['documentation', 'detail', 'insertText']) {
                    if (key in row) {
                        harvestedRow[key] = row[key];
                    }
                }
                return harvestedRow;
            });
        }
    }
    return out;
}

function writeJson(filePath, value) {
    fs.writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

function evalNodeCatalogs(serverSource) {
    const commandChunk = sliceInclusive(
        serverSource,
        'const commandValidations = {',
        '\nconst commandNames = Object.keys(commandValidations);',
    );
    const keywordChunk = sliceInclusive(
        serverSource,
        'const keywords = [',
        '\nconst keywordLabelsSet = new Set(keywords.map(keyword => keyword.label));',
    );
    const typeMapChunk = sliceInclusive(
        serverSource,
        'const returnTypeMap = {',
        '\n// Define parameter configurations for different commands',
    );
    const parameterChunk = sliceInclusive(
        serverSource,
        'const parameterConfigurations = {',
        '\n//end of constants/predefined variables',
    );

    const sandbox = {
        Infinity,
        isValidNormalVariable() { return true; },
        isValidStringVariable() { return true; },
        isValidAnyVariable() { return true; },
        isValidStringExpression() { return true; },
        isValidVariableOrCommand() { return true; },
        validateDbcreateFieldDefinitions() { return null; },
    };
    vm.createContext(sandbox);
    // `const` bindings stay in the script scope; copy them onto the sandbox.
    vm.runInContext(
        `${commandChunk}\n${keywordChunk}\n${typeMapChunk}\n${parameterChunk}
this.parameterConfigurations = parameterConfigurations;
this.commandValidations = commandValidations;
this.keywords = keywords;
this.returnTypeMap = returnTypeMap;
this.inputParamTypeMap = inputParamTypeMap;
this.paramTypeMap = paramTypeMap;
this.multiParamTypeMap = multiParamTypeMap;`,
        sandbox,
    );

    return {
        commandValidations: sandbox.commandValidations,
        keywords: sandbox.keywords,
        returnTypeMap: sandbox.returnTypeMap,
        inputParamTypeMap: sandbox.inputParamTypeMap,
        paramTypeMap: sandbox.paramTypeMap,
        multiParamTypeMap: sandbox.multiParamTypeMap,
        parameterConfigurations: sandbox.parameterConfigurations,
    };
}

function sliceInclusive(source, startMarker, endMarker) {
    const start = source.indexOf(startMarker);
    if (start < 0) {
        throw new Error(`Missing start marker: ${startMarker}`);
    }
    const end = source.indexOf(endMarker, start);
    if (end < 0) {
        throw new Error(`Missing end marker: ${endMarker}`);
    }
    return source.slice(start, end);
}

function harvestCommand(name, entry) {
    const row = {
        structure: harvestStructure(entry.structure),
    };
    if (entry.strictMode) {
        row.strictMode = JSON.parse(JSON.stringify(entry.strictMode));
    }
    if (entry.cleanupRules) {
        row.cleanupRules = JSON.parse(JSON.stringify(entry.cleanupRules));
    }
    if (CUSTOM_VALIDATORS.includes(name)) {
        row.customValidator = name;
        return row;
    }
    row.tableValidator = parseTableValidator(name, entry.validation);
    return row;
}

// Native-only command catalog changes over the frozen Node harvest
// (docs/adr/0011-findstr-value-expressions.md).
//
// Additions: a command Node lacks, cloned from a harvested one with every
// whole-word mention of the source name in its messages renamed.
const NATIVE_COMMAND_ADDITIONS = Object.freeze({
    findstrr: { cloneOf: 'findstrri' },
});

// Structure fields merged over the harvested (or added) entry.
// valueExpression: in an assignment, an operator plus a math expression after
// the call's `)` is part of the assigned value, not parameters after parentheses.
const FINDSTR_STRUCTURE = Object.freeze({ paramsOutside: 0, maxParamsOutside: 0, valueExpression: true });
const NATIVE_STRUCTURE_OVERRIDES = Object.freeze({
    findstr: FINDSTR_STRUCTURE,
    findstri: FINDSTR_STRUCTURE,
    findstrr: FINDSTR_STRUCTURE,
    findstrri: FINDSTR_STRUCTURE,
    // docs/adr/0016: `dbdelete "./db"` / `dbdelete DbId` take no parentheses (vxbd320
    // statements never write them); `dbgetactrow("REG")` does.
    dbdelete: { hasParentheses: false, minParamsInside: 0, maxParamsInside: 0, paramsOutside: 1, maxParamsOutside: 1 },
    dbgetactrow: { hasParentheses: true },
});

// Table validators replaced wholesale on the harvested entry (docs/adr/0016).
const NATIVE_TABLE_VALIDATOR_OVERRIDES = Object.freeze({
    dbdelete: {
        tooFewAfter: 'dbdelete requires 1 parameter',
        after: [
            {
                index: 0,
                kind: 'string-or-variable',
                variableKind: 'any variable',
                required: true,
                invalid: 'Parameter must be a valid string or variable in dbdelete',
            },
        ],
    },
});

// findstr* return a 1-based character position (0 when not found), not a boolean.
const NATIVE_RETURN_TYPE_OVERRIDES = Object.freeze({
    findstr: 'value',
    findstri: 'value',
    findstrr: 'value',
    findstrri: 'value',
});

function applyNativeCommandOverrides(commands) {
    const out = {};
    for (const [name, row] of Object.entries(commands)) {
        out[name] = row;
        for (const [added, { cloneOf }] of Object.entries(NATIVE_COMMAND_ADDITIONS)) {
            if (cloneOf !== name) {
                continue;
            }
            if (Object.prototype.hasOwnProperty.call(commands, added)) {
                throw new Error(`Native addition ${added} is now harvested from Node; drop the addition`);
            }
            const pattern = new RegExp(`\\b${cloneOf}\\b`, 'g');
            out[added] = JSON.parse(JSON.stringify(row).replace(pattern, added));
        }
    }
    for (const [added, { cloneOf }] of Object.entries(NATIVE_COMMAND_ADDITIONS)) {
        if (!out[added]) {
            throw new Error(`Native addition ${added}: clone source ${cloneOf} not harvested`);
        }
    }
    for (const [name, fields] of Object.entries(NATIVE_STRUCTURE_OVERRIDES)) {
        if (!out[name]) {
            throw new Error(`Native structure override for unknown command ${name}`);
        }
        out[name] = { ...out[name], structure: { ...out[name].structure, ...fields } };
    }
    for (const [name, tableValidator] of Object.entries(NATIVE_TABLE_VALIDATOR_OVERRIDES)) {
        if (!out[name] || !out[name].tableValidator) {
            throw new Error(`Native table-validator override for ${name}, which has no harvested table validator`);
        }
        out[name] = { ...out[name], tableValidator: JSON.parse(JSON.stringify(tableValidator)) };
    }
    return out;
}

function applyNativeReturnTypeOverrides(returnTypeMap) {
    const out = { ...returnTypeMap };
    for (const [name, type] of Object.entries(NATIVE_RETURN_TYPE_OVERRIDES)) {
        if (!Object.prototype.hasOwnProperty.call(out, name)) {
            throw new Error(`Native return-type override for ${name}, which Node does not map`);
        }
        out[name] = type;
    }
    return out;
}

function harvestStructure(structure) {
    const out = {};
    for (const key of [
        'hasAssignment',
        'hasParentheses',
        'minParamsInside',
        'maxParamsInside',
        'paramsOutside',
        'maxParamsOutside',
        'acceptSpacesAsSeparators',
    ]) {
        if (!Object.prototype.hasOwnProperty.call(structure, key)) {
            continue;
        }
        out[key] = encodeArity(structure[key]);
    }
    return out;
}

function encodeArity(value) {
    if (value === Infinity) {
        return 'unbounded';
    }
    return value;
}

// Native-only catalog corrections applied over the frozen Node harvest
// (docs/adr/0003, docs/adr/0016). Keyed by the Node label.
// insertText: snippets list required parameters only, quote string slots, and
// leave the assignment to the user.
const NATIVE_KEYWORD_OVERRIDES = Object.freeze({
    '$DIR_SYSTEM&': { label: '$DIR_SYSTEM' },
    '$DIR_SYMBOLS': { detail: 'returns symbols directory -custom/system' },
    get_obj_param: { insertText: 'get_obj_param(${1:in_Obj},"${2:FIELD}")' },
    set_djmember: { insertText: 'set_djmember(${1:in_Joint}) ${2:in_Object},"${3:ROLE}"' },
    new_feature: { insertText: 'new_feature("${1:TYPE}","${2:0}","${3:0}")' },
});

function harvestKeywords(keywords) {
    return keywords.map((keyword) => {
        const override = NATIVE_KEYWORD_OVERRIDES[keyword.label] || {};
        const item = {
            label: override.label || keyword.label,
            detail: override.detail || keyword.detail,
        };
        if (keyword.documentation !== undefined) {
            item.documentation = keyword.documentation;
        }
        if (override.insertText !== undefined) {
            if (keyword.insertText === undefined) {
                throw new Error(`Native insertText override for ${keyword.label}, which Node gives no snippet`);
            }
            item.insertText = override.insertText;
        } else if (keyword.insertText !== undefined) {
            item.insertText = keyword.insertText;
        }
        return item;
    });
}

function stringifyNumericKeys(map) {
    const out = {};
    for (const [command, slots] of Object.entries(map)) {
        if (slots && typeof slots === 'object' && !Array.isArray(slots)) {
            const nested = {};
            for (const [slot, type] of Object.entries(slots)) {
                nested[String(slot)] = type;
            }
            out[command] = nested;
        } else {
            out[command] = slots;
        }
    }
    return out;
}

function parseTableValidator(name, validationFn) {
    if (typeof validationFn !== 'function') {
        throw new Error(`${name}: missing validation()`);
    }
    let body = normalizeValidationBody(extractFunctionBody(validationFn.toString()));
    const table = {
        assignment: null,
        tooFewInside: undefined,
        tooManyInside: undefined,
        tooFewAfter: undefined,
        tooManyAfter: undefined,
        inside: [],
        after: [],
        insideTail: undefined,
        afterTail: undefined,
    };

    while (body.length > 0) {
        if (consume(body, /^return\s+null;?/)) {
            body = consume(body, /^return\s+null;?/).rest;
            continue;
        }

        const forStmt = matchFor(body);
        if (forStmt) {
            applyFor(name, table, forStmt);
            body = forStmt.rest;
            continue;
        }

        const ifStmt = matchIf(body);
        if (ifStmt) {
            applyIf(name, table, ifStmt);
            body = ifStmt.rest;
            continue;
        }

        throw new Error(`${name}: unparsed validation remainder: ${body.slice(0, 240)}`);
    }

    return compactTable(table);
}

function extractFunctionBody(src) {
    const start = src.indexOf('{');
    const end = src.lastIndexOf('}');
    if (start < 0 || end < 0 || end <= start) {
        throw new Error(`Cannot extract function body: ${src.slice(0, 80)}`);
    }
    return src.slice(start + 1, end);
}

function normalizeValidationBody(src) {
    const withoutComments = src
        .replace(/\/\*[\s\S]*?\*\//g, ' ')
        .replace(/(^|[^:\\\w])\/\/[^\n]*/g, '$1');
    return withoutComments.replace(/\s+/g, ' ').trim();
}

function consume(src, re) {
    const match = src.match(re);
    if (!match || match.index !== 0) {
        return null;
    }
    return { match, rest: src.slice(match[0].length).trim() };
}

function matchFor(src) {
    const header = consume(
        src,
        /^for\s*\(\s*(?:let|var)\s+i\s*=\s*(\d+)\s*;\s*i\s*<\s*(?:parsed\.(insideParams|afterParams)\.length|(\d+))\s*;\s*i\+\+\s*\)\s*/,
    );
    if (!header) {
        return null;
    }
    const block = takeBlockOrStatement(header.rest);
    const inner = consume(
        block.inner,
        /^if\s*\(\s*(.+?)\s*\)\s*\{\s*return\s+(`[\s\S]*?`|"[^"]*")\s*;?\s*\}\s*;?\s*$/,
    );
    if (!inner) {
        throw new Error(`Unrecognized for-loop body: ${block.inner.slice(0, 200)}`);
    }
    return {
        start: Number(header.match[1]),
        list: header.match[2] || null,
        bound: header.match[3] ? Number(header.match[3]) : null,
        kind: parseKindCondition(inner.match[1]),
        invalid: decodeReturn(inner.match[2]),
        rest: block.rest,
    };
}

function matchIf(src) {
    const opened = consume(src, /^if\s*\(/);
    if (!opened) {
        return null;
    }
    const cond = takeBalanced(opened.rest, '(', ')', true);
    const afterCond = cond.rest.trim();
    const thenPart = takeBlockOrStatement(afterCond);
    return {
        condition: cond.inner.trim(),
        thenInner: thenPart.inner.trim(),
        rest: thenPart.rest,
    };
}

function takeBlockOrStatement(src) {
    const trimmed = src.trim();
    if (trimmed.startsWith('{')) {
        const block = takeBalanced(trimmed, '{', '}', false);
        return { inner: block.inner.trim(), rest: block.rest.trim() };
    }
    const ended = trimmed.match(/^(return\s+(?:`[\s\S]*?`|"[^"]*"|\{[\s\S]*?\});?)/);
    if (!ended) {
        throw new Error(`Expected block or return: ${trimmed.slice(0, 160)}`);
    }
    return { inner: ended[1], rest: trimmed.slice(ended[1].length).trim() };
}

function takeBalanced(src, open, close, alreadyOpened) {
    let depth = alreadyOpened ? 1 : 0;
    let i = 0;
    while (i < src.length) {
        const ch = src[i];
        if (ch === '"' || ch === "'" || ch === '`') {
            i = skipQuoted(src, i);
            continue;
        }
        if (ch === '/' && src[i + 1] === '/') {
            const nl = src.indexOf('\n', i);
            i = nl < 0 ? src.length : nl + 1;
            continue;
        }
        if (ch === open) {
            depth += 1;
        } else if (ch === close) {
            depth -= 1;
            if (depth === 0) {
                const innerStart = alreadyOpened ? 0 : 1;
                return {
                    inner: src.slice(innerStart, i),
                    rest: src.slice(i + 1),
                };
            }
        }
        i += 1;
    }
    throw new Error(`Unbalanced ${open}${close}: ${src.slice(0, 160)}`);
}

function skipQuoted(src, i) {
    const q = src[i];
    i += 1;
    while (i < src.length) {
        if (src[i] === '\\') {
            i += 2;
            continue;
        }
        if (src[i] === q) {
            return i + 1;
        }
        i += 1;
    }
    throw new Error('Unterminated string');
}

function applyFor(name, table, stmt) {
    const list = stmt.list || stmt.kind.list;
    if (!list) {
        throw new Error(`${name}: for-loop does not name insideParams or afterParams`);
    }
    if (stmt.bound !== null) {
        const slots = [];
        for (let i = stmt.start; i < stmt.bound; i += 1) {
            slots.push({
                index: i,
                kind: stmt.kind.kind,
                ...(stmt.kind.variableKind ? { variableKind: stmt.kind.variableKind } : {}),
                required: true,
                invalid: materializeIndexMessage(stmt.invalid, i + 1),
            });
        }
        appendSlots(table, list === 'afterParams' ? 'after' : 'inside', slots);
        return;
    }
    const tail = {
        from: stmt.start,
        kind: stmt.kind.kind,
        ...(stmt.kind.variableKind ? { variableKind: stmt.kind.variableKind } : {}),
        invalid: templatizeIndexMessage(stmt.invalid),
    };
    if (list === 'insideParams') {
        table.insideTail = tail;
    } else {
        table.afterTail = tail;
    }
}

function appendSlots(table, target, slots) {
    const list = target === 'after' ? table.after : table.inside;
    for (const slot of slots) {
        list.push(slot);
    }
}

function applyIf(name, table, stmt) {
    const cond = stmt.condition;
    const thenInner = stmt.thenInner;

    if (cond === '!parsed.assignment') {
        ensureAssignment(table).presence = 'required';
        ensureAssignment(table).missing = decodeReturnFromThen(thenInner);
        return;
    }

    const assignOptional = cond.match(/^parsed\.assignment\s*&&\s*(.+)$/);
    if (assignOptional) {
        const kind = parseKindCondition(assignOptional[1]);
        const assignment = ensureAssignment(table);
        assignment.presence = assignment.presence || 'optional';
        applyAssignmentKind(assignment, kind);
        assignment.invalid = decodeReturnFromThen(thenInner);
        return;
    }

    const assignKind = cond.match(/^!isValid\w+\(parsed\.assignment\)/);
    if (assignKind) {
        const kind = parseKindCondition(cond);
        const assignment = ensureAssignment(table);
        assignment.presence = assignment.presence || 'required';
        applyAssignmentKind(assignment, kind);
        assignment.invalid = decodeReturnFromThen(thenInner);
        return;
    }

    const arity = cond.match(/^parsed\.(insideParams|afterParams)\.length\s*(<|<=|>|>=|===|==|!==|!=)\s*(\d+)$/);
    if (arity) {
        const list = arity[1];
        const op = arity[2];
        const n = Number(arity[3]);
        const nested = maybeNestedKindIf(thenInner);
        if (nested && (op === '===' || op === '==' || op === '>=' || op === '>')) {
            const index = nested.index !== undefined ? nested.index : n - 1;
            const slot = {
                index,
                kind: nested.kind.kind,
                ...(nested.kind.variableKind ? { variableKind: nested.kind.variableKind } : {}),
                required: false,
                invalid: nested.invalid,
            };
            (list === 'insideParams' ? table.inside : table.after).push(slot);
            return;
        }
        if (op === '===' || op === '==') {
            throw new Error(`${name}: equality arity without nested kind: ${cond} => ${thenInner}`);
        }
        const message = decodeReturnFromThen(thenInner);
        const tooFew = op === '<' || op === '<=' || op === '!=' || op === '!==';
        const tooMany = op === '>' || op === '>=' || op === '!=' || op === '!==';
        if (list === 'insideParams') {
            if (tooFew) {
                table.tooFewInside = message;
            }
            if (tooMany) {
                table.tooManyInside = message;
            }
        } else {
            if (tooFew) {
                table.tooFewAfter = message;
            }
            if (tooMany) {
                table.tooManyAfter = message;
            }
        }
        return;
    }

    const guardedKind = cond.match(
        /^parsed\.(insideParams|afterParams)\.length\s*(>=|>|===|==)\s*(\d+)\s*&&\s*(.+)$/,
    );
    if (guardedKind) {
        const list = guardedKind[1];
        const n = Number(guardedKind[3]);
        const kind = parseKindCondition(guardedKind[4]);
        const index = kind.index !== undefined ? kind.index : n - 1;
        const slot = {
            index,
            kind: kind.kind,
            ...(kind.variableKind ? { variableKind: kind.variableKind } : {}),
            required: false,
            invalid: decodeReturnFromThen(thenInner),
        };
        (list === 'insideParams' ? table.inside : table.after).push(slot);
        return;
    }

    const truthySlot = cond.match(/^parsed\.(insideParams|afterParams)\[(\d+)\]\s*&&\s*(.+)$/);
    if (truthySlot) {
        const kind = parseKindCondition(truthySlot[3]);
        const slot = {
            index: Number(truthySlot[2]),
            kind: kind.kind,
            ...(kind.variableKind ? { variableKind: kind.variableKind } : {}),
            required: false,
            invalid: decodeReturnFromThen(thenInner),
        };
        (truthySlot[1] === 'insideParams' ? table.inside : table.after).push(slot);
        return;
    }

    const requiredSlot = parseKindCondition(cond);
    if (requiredSlot && requiredSlot.index !== undefined && requiredSlot.list) {
        const slot = {
            index: requiredSlot.index,
            kind: requiredSlot.kind,
            ...(requiredSlot.variableKind ? { variableKind: requiredSlot.variableKind } : {}),
            required: true,
            invalid: decodeReturnFromThen(thenInner),
        };
        (requiredSlot.list === 'insideParams' ? table.inside : table.after).push(slot);
        return;
    }

    throw new Error(`${name}: unrecognized if (${cond}) => ${thenInner.slice(0, 180)}`);
}

function maybeNestedKindIf(thenInner) {
    const nested = matchIf(thenInner);
    if (!nested) {
        return null;
    }
    if (nested.rest && nested.rest.length > 0) {
        return null;
    }
    const kind = parseKindCondition(nested.condition);
    if (!kind) {
        return null;
    }
    return {
        kind,
        index: kind.index,
        invalid: decodeReturnFromThen(nested.thenInner),
    };
}

function ensureAssignment(table) {
    if (!table.assignment) {
        table.assignment = {};
    }
    return table.assignment;
}

function applyAssignmentKind(assignment, kind) {
    assignment.kind = kind.kind;
    if (kind.variableKind) {
        assignment.variableKind = kind.variableKind;
    }
}

function parseKindCondition(cond) {
    const text = cond.trim();
    const digit = text.match(
        /^!\(\s*\/\^\\d\+\$\/\.test\(parsed\.(insideParams|afterParams)\[(\d+)\]\)\s*\|\|\s*isValidNormalVariable\(parsed\.(?:insideParams|afterParams)\[\d+\]\)\s*\)$/,
    );
    if (digit) {
        return {
            kind: 'digit literal or variable',
            list: digit[1],
            index: Number(digit[2]),
        };
    }

    const predicates = [];
    const slotRe =
        /!?isValid(NormalVariable|StringVariable|AnyVariable|StringExpression)\(parsed\.(insideParams|afterParams|assignment)(?:\[(\d+|i)\])?\)/g;
    let match;
    let lastIndex = 0;
    const stripped = text.replace(/\s+/g, ' ');
    while ((match = slotRe.exec(stripped))) {
        predicates.push({
            fn: `isValid${match[1]}`,
            list: match[2] === 'assignment' ? 'assignment' : match[2],
            index: match[3] === undefined || match[3] === 'i' ? undefined : Number(match[3]),
            negated: stripped[match.index] === '!',
        });
        lastIndex = slotRe.lastIndex;
    }
    if (predicates.length === 0) {
        return null;
    }

    const leftoverCheck = stripped
        .replace(
            /!?isValid(?:NormalVariable|StringVariable|AnyVariable|StringExpression)\(parsed\.(?:insideParams|afterParams|assignment)(?:\[(?:\d+|i)\])?\)/g,
            '',
        )
        .replace(/&&|\|\||!|\(|\)/g, '')
        .trim();
    if (leftoverCheck) {
        throw new Error(`Unrecognized kind remainder '${leftoverCheck}' in ${text}`);
    }

    const kinds = predicates.map((p) => KIND_BY_PREDICATE[p.fn]);
    const combined = combineKinds(kinds);
    const first = predicates[0];
    return {
        ...combined,
        list: first.list,
        index: first.index,
    };
}

function combineKinds(kinds) {
    const unique = [...new Set(kinds)];
    if (unique.length === 1) {
        return { kind: unique[0] };
    }
    const set = new Set(unique);
    if (set.has('normal variable') && set.has('string variable') && unique.length === 2) {
        return { kind: 'any variable' };
    }
    if (set.has('any variable') && set.has('string expression') && unique.length === 2) {
        return { kind: 'string-or-variable', variableKind: 'any variable' };
    }
    if (set.has('normal variable') && set.has('string expression') && unique.length === 2) {
        return { kind: 'string-or-variable', variableKind: 'normal variable' };
    }
    throw new Error(`Cannot combine kinds: ${unique.join(', ')}`);
}

function decodeReturnFromThen(thenInner) {
    const direct = thenInner.match(/^return\s+(`[\s\S]*?`|"[^"]*")\s*;?$/);
    if (direct) {
        return decodeReturn(direct[1]);
    }
    const blocked = thenInner.match(/^return\s+(`[\s\S]*?`|"[^"]*")\s*;?$/);
    if (blocked) {
        return decodeReturn(blocked[1]);
    }
    // `{ return "x"; }` already stripped to inner by takeBlockOrStatement for nested
    const innerReturn = thenInner.match(/return\s+(`[\s\S]*?`|"[^"]*")\s*;?/);
    if (innerReturn) {
        return decodeReturn(innerReturn[1]);
    }
    throw new Error(`Cannot decode return from: ${thenInner.slice(0, 160)}`);
}

function decodeReturn(literal) {
    if (literal.startsWith('"')) {
        return JSON.parse(literal);
    }
    if (literal.startsWith('`')) {
        return literal.slice(1, -1);
    }
    throw new Error(`Unknown return literal: ${literal}`);
}

function templatizeIndexMessage(message) {
    return message
        .replace(/\$\{i\s*\+\s*1\}/g, '{n}')
        .replace(/\$\{i\+1\}/g, '{n}');
}

function materializeIndexMessage(message, n) {
    return templatizeIndexMessage(message).replace(/\{n\}/g, String(n));
}

function compactTable(table) {
    const out = {};
    if (table.assignment && Object.keys(table.assignment).length > 0) {
        if (table.assignment.list || table.assignment.index !== undefined) {
            throw new Error('assignment leaked parser fields');
        }
        out.assignment = table.assignment;
    }
    if (table.tooFewInside) {
        out.tooFewInside = table.tooFewInside;
    }
    if (table.tooManyInside) {
        out.tooManyInside = table.tooManyInside;
    }
    if (table.tooFewAfter) {
        out.tooFewAfter = table.tooFewAfter;
    }
    if (table.tooManyAfter) {
        out.tooManyAfter = table.tooManyAfter;
    }
    if (table.inside.length > 0) {
        out.inside = sortSlots(table.inside);
    }
    if (table.after.length > 0) {
        out.after = sortSlots(table.after);
    }
    if (table.insideTail) {
        out.insideTail = table.insideTail;
    }
    if (table.afterTail) {
        out.afterTail = table.afterTail;
    }
    return out;
}

function sortSlots(slots) {
    return [...slots].sort((a, b) => a.index - b.index);
}

function assertHarvest(harvested) {
    const objectParameterCommands = Object.keys(harvested.objectParameters).join(',');
    if (objectParameterCommands !== 'get_obj_param,get_material_param,get_area_param,get_section_param') {
        throw new Error(`Unexpected object-parameter commands: ${objectParameterCommands}`);
    }
    const names = Object.keys(harvested.commands);
    if (names.length !== 245) {
        throw new Error(`Expected 245 command keys, got ${names.length}`);
    }
    if (names.includes('call')) {
        throw new Error('call must not be a command-catalog key');
    }
    const custom = names.filter((name) => harvested.commands[name].customValidator);
    const table = names.filter((name) => harvested.commands[name].tableValidator);
    if (custom.length !== 5) {
        throw new Error(`Expected 5 custom validators, got ${custom.join(', ')}`);
    }
    if (table.length !== 240) {
        throw new Error(`Expected 240 table validators, got ${table.length}`);
    }
    for (const name of CUSTOM_VALIDATORS) {
        const row = harvested.commands[name];
        if (row.customValidator !== name || row.tableValidator) {
            throw new Error(`${name} must be customValidator only`);
        }
    }
    for (const name of table) {
        const row = harvested.commands[name];
        if (row.customValidator) {
            throw new Error(`${name} has both validators`);
        }
    }

    const unbounded = names.filter((name) => {
        const s = harvested.commands[name].structure;
        return s.maxParamsInside === 'unbounded' || s.maxParamsOutside === 'unbounded';
    });
    const expectedUnbounded = ['set_sheet_shape', 'new_feature', 'add_aux_task', 'new_ncaccessory'];
    if (unbounded.sort().join(',') !== expectedUnbounded.slice().sort().join(',')) {
        throw new Error(`Unexpected unbounded arity: ${unbounded.join(', ')}`);
    }

    const labels = harvested.keywords.map((k) => k.label);
    for (const dup of ['ddrevid_last', 'fileinfo_to_meta']) {
        if (labels.filter((label) => label === dup).length < 2) {
            throw new Error(`Keyword catalog lost duplicate label ${dup}`);
        }
    }

    const writes = harvested.commandTypeWrites;
    for (const key of ['Xlimit_max', 'Xlimit_min', 'Ylimit_max', 'Ylimit_min']) {
        if (!Object.prototype.hasOwnProperty.call(writes.returnTypeMap, key)
            && !hasMixedCase(writes, key)) {
            // Ticket 41: mixed-case keys live on the maps Node wrote. Probe which map.
        }
    }
    if (!hasMixedCase(writes, 'Xlimit_max')) {
        throw new Error('command-type-writes lost mixed-case Xlimit_max');
    }
    if (writes.paramTypeMap.get_edge_dir && writes.paramTypeMap.get_edge_dir['1']) {
        throw new Error('get_edge_dir must omit slot 1');
    }
    if (!writes.paramTypeMap.get_edge_dir || writes.paramTypeMap.get_edge_dir['2'] !== 'dvector') {
        throw new Error('get_edge_dir slot 2 missing');
    }
}

function hasMixedCase(writes, key) {
    return ['returnTypeMap', 'inputParamTypeMap', 'paramTypeMap', 'multiParamTypeMap']
        .some((mapName) => Object.prototype.hasOwnProperty.call(writes[mapName], key));
}

function summarize(harvested) {
    const names = Object.keys(harvested.commands);
    const custom = names.filter((name) => harvested.commands[name].customValidator);
    return [
        `Harvested ${names.length} commands (${names.length - custom.length} table, ${custom.length} custom),`,
        `${harvested.keywords.length} keyword-catalog entries,`,
        `command-type-writes maps ${Object.keys(harvested.commandTypeWrites.returnTypeMap).length}/` +
            `${Object.keys(harvested.commandTypeWrites.inputParamTypeMap).length}/` +
            `${Object.keys(harvested.commandTypeWrites.paramTypeMap).length}/` +
            `${Object.keys(harvested.commandTypeWrites.multiParamTypeMap).length}`,
        `keys, ${Object.keys(harvested.objectParameters).length} object-parameter commands.`,
        `Wrote server/catalog/{commands,keywords,command-type-writes,object-parameters}.json`,
        `and server/src/generated/{catalog_data.h,command_catalog_data.cpp,keyword_catalog_data.cpp,command_type_writes_data.cpp,object_parameters_data.cpp}.`,
    ].join(' ');
}

